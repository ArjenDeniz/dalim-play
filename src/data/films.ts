const slug = (s: string) =>
  s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/ı/g, 'i')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')

const f = (title: string, year: number, genres: string, trTitle?: string): Film => ({
  id: `${slug(title)}-${year}`,
  title,
  trTitle,
  year,
  genres: genres.split(' ') as Genre[],
})

